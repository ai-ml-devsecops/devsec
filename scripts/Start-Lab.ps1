[CmdletBinding()]
param(
    # Wipe the VMs and fully re-provision from scratch, then re-snapshot.
    [switch]$Rebuild,
    # Revert to the last known-good snapshot even if the lab is already running.
    [switch]$Reset
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$nodes = @("gitlab", "runner", "app", "jumpbox")
$labNodes = @("gitlab", "runner", "app")
$snapshotName = "initial-ready"
$remoteRoot = "/opt/devsecops-lab"

function Get-NodeIp([string]$Node) {
    $raw = & vagrant ssh $Node -c "hostname -I"
    if ([string]::IsNullOrWhiteSpace($raw)) {
        throw "Could not determine the private-network IP address for '$Node'."
    }
    return $raw.Trim().Split(" ")[0].Trim()
}

function Test-SnapshotExists([string]$Node) {
    $list = & vagrant snapshot list $Node 2>$null
    return ($LASTEXITCODE -eq 0) -and ($list -match [regex]::Escape($snapshotName))
}

function Restore-Lab {
    Write-Host "Restoring lab to the '$snapshotName' snapshot..." -ForegroundColor Cyan
    foreach ($node in $nodes) {
        & vagrant snapshot restore $node $snapshotName
        if ($LASTEXITCODE -ne 0) { throw "Failed to restore snapshot for '$node'." }
    }
}

function Invoke-FullProvision {
    Write-Host "Booting lab VMs..." -ForegroundColor Cyan
    & vagrant up --provider=vmware_desktop
    if ($LASTEXITCODE -ne 0) { throw "vagrant up failed." }

    Write-Host "Collecting node IP addresses..." -ForegroundColor Cyan
    $ips = @{}
    foreach ($node in $labNodes) {
        $ips[$node] = Get-NodeIp $node
    }

    Write-Host "Writing Ansible inventory..." -ForegroundColor Cyan
    $inventoryPath = Join-Path $root "ansible\inventory\runtime.yml"
    $lines = @(
        "# Generated by Start-Lab.ps1 - do not edit by hand."
        "all:"
        "  vars:"
        "    ansible_user: vagrant"
        "  children:"
        "    lab:"
        "      hosts:"
    )
    foreach ($node in $labNodes) {
        $lines += "        ${node}:"
        $lines += "          ansible_host: $($ips[$node])"
        $lines += "          ansible_port: 22"
        $lines += "          ansible_ssh_private_key_file: $remoteRoot/keys/$node.pem"
    }
    $lines | Set-Content -Encoding ascii $inventoryPath

    Write-Host "Staging SSH keys..." -ForegroundColor Cyan
    $stagingDir = Join-Path $root ".staging\keys"
    if (Test-Path $stagingDir) { Remove-Item $stagingDir -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $stagingDir | Out-Null
    foreach ($node in $labNodes) {
        $keySource = Join-Path $root ".vagrant\machines\$node\vmware_desktop\private_key"
        Copy-Item $keySource (Join-Path $stagingDir "$node.pem")
    }

    Write-Host "Uploading Ansible content to the jumpbox controller..." -ForegroundColor Cyan
    & vagrant ssh jumpbox -c "sudo install -d -o vagrant -g vagrant -m 0755 $remoteRoot $remoteRoot/keys $remoteRoot/ansible $remoteRoot/scripts"
    if ($LASTEXITCODE -ne 0) { throw "Could not create the jumpbox workspace." }
    & vagrant upload (Join-Path $root "ansible") "$remoteRoot/ansible" jumpbox
    if ($LASTEXITCODE -ne 0) { throw "Could not upload Ansible content to the jumpbox." }
    & vagrant upload (Join-Path $root "scripts") "$remoteRoot/scripts" jumpbox
    if ($LASTEXITCODE -ne 0) { throw "Could not upload scripts to the jumpbox." }
    foreach ($node in $labNodes) {
        & vagrant upload (Join-Path $stagingDir "$node.pem") "$remoteRoot/keys/$node.pem" jumpbox
        if ($LASTEXITCODE -ne 0) { throw "Could not upload the SSH key for '$node'." }
    }
    & vagrant ssh jumpbox -c "chmod 600 $remoteRoot/keys/*.pem"
    if ($LASTEXITCODE -ne 0) { throw "Could not secure the jumpbox SSH keys." }

    Write-Host "Installing Ansible on the jumpbox if needed..." -ForegroundColor Cyan
    & vagrant ssh jumpbox -c "command -v ansible-playbook >/dev/null || (sudo apt-get update && sudo env DEBIAN_FRONTEND=noninteractive apt-get install -y ansible-core)"
    if ($LASTEXITCODE -ne 0) { throw "Could not install Ansible on the jumpbox." }

    Write-Host "Running the Ansible bootstrap from the jumpbox (this is the slow, one-time step)..." -ForegroundColor Cyan
    & vagrant ssh jumpbox -c "cd $remoteRoot/ansible && ansible-playbook -i inventory/runtime.yml playbooks/site.yml"
    if ($LASTEXITCODE -ne 0) { throw "Ansible bootstrap failed. Fix the reported task and re-run Start-Lab.ps1." }

    Write-Host "Snapshotting the lab as '$snapshotName'..." -ForegroundColor Cyan
    foreach ($node in $nodes) {
        & vagrant snapshot save $node $snapshotName --force
        if ($LASTEXITCODE -ne 0) { throw "Failed to snapshot '$node'." }
    }
}

Push-Location $root
try {
    if ($Rebuild) {
        Write-Host "Destroying existing VMs for a clean rebuild..." -ForegroundColor Yellow
        & vagrant destroy -f
        Invoke-FullProvision
    }
    elseif ($Reset) {
        Restore-Lab
    }
    else {
        $hasSnapshot = ($nodes | ForEach-Object { Test-SnapshotExists $_ }) -notcontains $false
        if ($hasSnapshot) {
            Restore-Lab
        }
        else {
            Invoke-FullProvision
        }
    }

    Write-Host "`n--- Lab Access Info ---" -ForegroundColor Green
    foreach ($node in $nodes) {
        $ip = Get-NodeIp $node
        Write-Host "$node`t-> http://$ip"
    }
    Write-Host "-----------------------`n"
    Write-Host "GitLab project: http://<gitlab-ip>/pdso/django.nv"
    Write-Host "Target app:     http://<app-ip>:8000"
}
finally {
    Pop-Location
}
